// Generate src/assets.js: the registry, tokens, EFN logo, client wordmarks and the ticker sample embedded as one
// ES module, so apps get a ready renderer with a plain import (no fetch, no JSON-module support, no bundler
// config). The file is committed so installs from git need no build step.
// Usage: node scripts/build-assets.js          regenerate
//        node scripts/build-assets.js --check  exit 1 if src/assets.js is out of date (run before committing)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const json = (rel) => JSON.parse(read(rel));

const registry = json('data/element-registry.json');
const tokens = json('data/design-tokens.json');
const sample = json('data/samples/ticker-payload.json');
const efnLogoSvg = read(registry.components.find(c => c.id === 'logo-line-logo').asset);
const wordmarks = Object.fromEntries(registry.components.find(c => c.id === 'logo-box').variants
  .filter(v => v.clientWordmark && v.clientWordmark.supplied).map(v => [v.id, read(v.clientWordmark.file)]));

const out = `// GENERATED by scripts/build-assets.js from data/ and assets/. Do not edit: change the source files and run
// \`npm run build\`.
export const registry = ${JSON.stringify(registry)};
export const tokens = ${JSON.stringify(tokens)};
export const efnLogoSvg = ${JSON.stringify(efnLogoSvg)};
export const wordmarks = ${JSON.stringify(wordmarks)};
export const sampleTickerPayload = ${JSON.stringify(sample)};
`;
const target = path.join(ROOT, 'src', 'assets.js');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) { console.error('src/assets.js is out of date: run `npm run build`'); process.exit(1); }
  console.log('src/assets.js is up to date');
} else {
  fs.writeFileSync(target, out);
  console.log(`src/assets.js: ${(out.length / 1024).toFixed(0)} KB (registry, tokens, EFN logo, ${Object.keys(wordmarks).length} wordmarks, ticker sample)`);
}
